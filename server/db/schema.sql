-- Café Noir backend schema. JSON columns hold nested/array data that the frontend already
-- treats as opaque (recipe lines, variants, order/reception/invoice line items, weekly HR
-- patterns) -- these are never queried relationally, only read/written whole.

-- --- RBAC (Roles & Permissions) -----------------------------------------------------------------
-- Permissions themselves are a fixed catalog defined in code (src/data/rbacModel.ts), not a table
-- here — adding a new permission is just appending to that array, no migration needed. Only the
-- ASSIGNMENT of permissions to a role is persisted (role_permissions). is_system marks a role that
-- can never be renamed/edited/deleted via the API (Super Admin only) so the app can never end up
-- with nobody able to manage roles.
CREATE TABLE IF NOT EXISTS roles (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT,
  is_system INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS role_permissions (
  role_id TEXT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  permission_key TEXT NOT NULL,
  PRIMARY KEY (role_id, permission_key)
);

-- Login accepts email OR phone OR cin + password (see server/routes/auth.ts) — email/phone are
-- optional (a CIN-only account is still valid) but unique when set, enforced by the partial unique
-- indexes below rather than a column-level UNIQUE, since SQLite would otherwise only allow a single
-- NULL row per UNIQUE column depending on version/config; a partial index is unambiguous.
-- must_change_password forces the change-password screen after a temporary password (generated by
-- a Super Admin, or by the one-time migration backfill for accounts that predate passwords) is
-- used to log in once. failed_login_attempts/locked_until implement a simple lockout after
-- repeated bad passwords — see server/routes/auth.ts's LOGIN_LOCKOUT_THRESHOLD.
-- employee_id links this login account to its HR record (src/components/EmployeesPage.tsx's
-- optional "Compte de connexion" section) — nullable, since some accounts (the original Super
-- Admin, or any admin/IT account) are never meant to have an HR employee record behind them.
-- is_active gates login independently of everything else (server/routes/auth.ts) — deactivating an
-- account never deletes it or anything it's linked to, just blocks future logins.
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  full_name TEXT NOT NULL,
  cin TEXT NOT NULL UNIQUE,
  email TEXT,
  phone TEXT,
  password_hash TEXT,
  password_updated_at TEXT,
  must_change_password INTEGER NOT NULL DEFAULT 0,
  failed_login_attempts INTEGER NOT NULL DEFAULT 0,
  locked_until TEXT,
  role_id TEXT REFERENCES roles(id),
  employee_id TEXT REFERENCES employees(id),
  is_active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL
);

-- The two partial unique indexes for email/phone are created in server/db/connection.ts instead of
-- here: CREATE TABLE IF NOT EXISTS above is a no-op on a database that already has a users table
-- (every pre-existing install), so an index statement referencing the email/phone columns run
-- directly from this file would fail with "no such column" before connection.ts's ALTER TABLE
-- migration ever gets a chance to add them. connection.ts creates both indexes right after that
-- migration runs, which is safe on a fresh database too (the columns already exist there from the
-- CREATE TABLE above).

-- revoked_at IS NULL means the session is currently active; it's never deleted on logout so
-- "Historique des connexions" can still show the login/logout event pair afterward.
CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  public_id TEXT UNIQUE,
